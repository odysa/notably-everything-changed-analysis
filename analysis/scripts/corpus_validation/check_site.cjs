const assert = require('node:assert/strict');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '../..');
const { JSDOM, VirtualConsole } = require('jsdom');
const errors=[];
const virtualConsole=new VirtualConsole();
virtualConsole.on('jsdomError', e=>errors.push(e.message));
const html=fs.readFileSync(path.join(ROOT,'site/public/index.html'),'utf8');
const dom=new JSDOM(html,{runScripts:'dangerously',pretendToBeVisual:true,url:'http://127.0.0.1:8765/',virtualConsole,
  beforeParse(w){w.matchMedia=()=>({matches:false,addEventListener(){},addListener(){}});}});
const w=dom.window,d=w.document,q=s=>d.querySelector(s);
assert.deepEqual(errors,[],'initialization errors');
